-- 16进制数据.lua - 发送转换插件（移植自 llcom user_script_send_convert/16进制数据.lua）
-- @name 发送转16进制
-- @desc 发送前把输入的16进制文本（如 "31 32 33 34"）解码成原始字节再发出。
-- 用法：启用后，在发送框输入 16 进制文本（空格 / 逗号 / 换行等非 16 进制字符
-- 会被自动过滤）。例如输入：
--     31 32 33 34
-- 实际发到串口的是 4 个字节 0x31 0x32 0x33 0x34。
--
-- 注意：
--   * 奇数个有效半字节时，最后一个半字节会被丢弃（与 llcom fromHex 一致）；
--   * 不要写 "0x" 前缀：'x' 会被过滤而 '0' 保留，导致多出一个半字节；
--   * 纯 ASCII 文本 "1234" 会被当作 0x12 0x34，请确认输入确实是 16 进制；
--   * 本脚本只做「文本 -> 字节」转换，不做任何校验；可与「发送追加换行回车」等
--     其它发送脚本叠加使用（多个发送脚本按文件名顺序依次转换）。

on.send(function(uartData)
    local bytes = uartData:fromHex()
    if #bytes == 0 then
        log.warn("16进制数据", "输入不含有效16进制字符，已取消本次发送")
        return nil   -- on.send 返回 nil 会中止本次发送
    end
    return bytes
end)
